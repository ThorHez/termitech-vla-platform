from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator
from vla_adapters.entrypoints import validate_entrypoint

from .dataset_profiles import DatasetProfile, validate_asset_metadata


class InputModel(BaseModel):
    model_config = ConfigDict(extra="forbid", allow_inf_nan=False)


class ProfileInput(InputModel):
    id: str = Field(min_length=1, max_length=200)
    name: str = Field(min_length=1, max_length=200)
    code_dir: str = Field(min_length=1, max_length=4096)
    python: str = Field(min_length=1, max_length=4096)
    adapter: str = Field(min_length=1, max_length=100)
    recipe: str | None = Field(default=None, max_length=255)
    execution_mode: Literal["native", "docker"] = "native"
    docker_image: str | None = None
    metadata: dict = Field(default_factory=dict)


class AgentConfigProfileInput(InputModel):
    """Browser-supplied fields only; trusted metadata is generated by the API."""

    id: str = Field(min_length=1, max_length=128, pattern=r"^[A-Za-z0-9_-]+$")
    name: str = Field(min_length=1, max_length=200)
    code_dir: str = Field(min_length=1, max_length=4096)
    python: str = Field(min_length=1, max_length=4096)
    adapter: Literal["smoke", "openpi-sft"]
    recipe: str | None = Field(default=None, max_length=255)
    execution_mode: Literal["native"] = "native"

    @field_validator("recipe", mode="before")
    @classmethod
    def normalize_recipe(cls, value):
        if isinstance(value, str):
            return value.strip() or None
        return value


class AgentConfigInput(InputModel):
    name: str = Field(min_length=1, max_length=200)
    control_plane_url: str | None = Field(default=None, min_length=1, max_length=2048)
    roots: list[str] = Field(min_length=1, max_length=100)
    output_root: str = Field(min_length=1, max_length=4096)
    state_dir: str = Field(min_length=1, max_length=4096)
    profiles: list[AgentConfigProfileInput] = Field(min_length=1, max_length=100)


class RegisterInput(InputModel):
    name: str = Field(min_length=1, max_length=200)
    hostname: str = Field(min_length=1, max_length=255)
    roots: list[str] = Field(min_length=1, max_length=100)
    output_root: str
    cache_root: str | None = Field(default=None, min_length=1, max_length=4096)
    profiles: list[ProfileInput] = Field(default_factory=list, max_length=100)


class NodeUpdateInput(InputModel):
    name: str = Field(min_length=1, max_length=200, strict=True)

    @field_validator("name", mode="before")
    @classmethod
    def trim_name(cls, value):
        return value.strip() if isinstance(value, str) else value

    @field_validator("name")
    @classmethod
    def reject_control_characters(cls, value):
        if any(ord(char) < 32 or 127 <= ord(char) <= 159 for char in value):
            raise ValueError("机器名称不能包含控制字符")
        return value


class GPUInput(InputModel):
    uuid: str = Field(min_length=1, max_length=200)
    name: str | None = None
    memory_total_mb: float | None = Field(default=None, ge=0)
    memory_used_mb: float | None = Field(default=None, ge=0)
    memory_free_mb: float | None = Field(default=None, ge=0)
    utilization_pct: float | None = Field(default=None, ge=0, le=100)
    processes: list[dict] | None = None


class ActiveAttemptInput(InputModel):
    attempt_id: str
    pid: int | None = None
    state: Literal["STARTING", "PREPARING", "RUNNING", "CANCELLING", "STOPPING", "UNKNOWN", "SUCCEEDED", "FAILED", "CANCELLED"]


class HeartbeatInput(InputModel):
    node_id: str
    gpus: list[GPUInput] = Field(default_factory=list, max_length=256)
    metrics: dict = Field(default_factory=dict)
    active_attempts: list[ActiveAttemptInput] = Field(default_factory=list, max_length=1000)
    profiles: list[ProfileInput] | None = Field(default=None, max_length=100)


class AssetInput(InputModel):
    name: str = Field(min_length=1, max_length=200)
    kind: Literal["DATASET", "MODEL", "NORM"]
    node_id: str
    path: str = Field(min_length=1, max_length=4096)
    version: str = Field(default="1", min_length=1, max_length=200)
    metadata: dict = Field(default_factory=dict)

    @model_validator(mode="after")
    def dataset_metadata(self):
        self.metadata = validate_asset_metadata(self.kind, self.metadata)
        return self


class AssetDatasetProfileInput(InputModel):
    dataset_profile: DatasetProfile


class PathSuggestInput(InputModel):
    prefix: str = Field(default="", max_length=4096)
    limit: int = Field(default=30, ge=1, le=50, strict=True)
    profile_id: str | None = Field(default=None, min_length=1, max_length=200)


class RecipeSuggestInput(InputModel):
    profile_id: str = Field(min_length=1, max_length=200)
    prefix: str = Field(default="", max_length=255)
    limit: int = Field(default=30, ge=1, le=50, strict=True)


class DatasetBindingInput(InputModel):
    dataset_asset_id: str = Field(min_length=1, max_length=200)
    norm_asset_id: str = Field(min_length=1, max_length=200)
    recipe_index: int | None = Field(default=None, ge=0, lt=64, strict=True)
    processor: dict | None = None
    weight: float = Field(gt=0, strict=True)

    @model_validator(mode="after")
    def validate_processor_choice(self):
        if (self.recipe_index is None) == (self.processor is None):
            raise ValueError("每组数据必须且只能选择独立数据处理器或旧版配方索引")
        if self.processor is not None:
            from vla_adapters.data_processors import normalize_processor
            self.processor = normalize_processor(self.processor)
        return self


class PreviewInput(InputModel):
    name: str = Field(min_length=1, max_length=200)
    node_id: str
    profile_id: str
    template_id: str
    training_stage: Literal["value", "offline_rl"] | None = None
    stage_config: dict | None = None
    auto_config: dict | None = None
    recipe: str | None = Field(default=None, max_length=255, pattern=r"^[A-Za-z0-9_-]+$")
    recipe_revision_id: str | None = Field(default=None, min_length=1, max_length=36)
    entrypoint: str | None = Field(default=None, min_length=1, max_length=4096)
    dataset_bindings: list[DatasetBindingInput] | None = Field(default=None, min_length=1, max_length=64)
    inputs: dict[str, str] = Field(default_factory=dict)
    parameters: dict = Field(default_factory=dict)
    gpu_count: int = Field(default=1, ge=0, le=256, strict=True)

    @field_validator("auto_config")
    @classmethod
    def validate_auto_config(cls, value):
        from vla_adapters.automatic_config import normalize_auto_config
        return normalize_auto_config(value)

    @field_validator("entrypoint")
    @classmethod
    def validate_entrypoint_path(cls, value):
        return validate_entrypoint(value)

    @field_validator("recipe", mode="before")
    @classmethod
    def normalize_recipe(cls, value):
        if isinstance(value, str):
            return value.strip() or None
        return value


class RunInput(InputModel):
    preflight_id: str
    confirmed_config_sha256: str | None = Field(default=None, pattern=r"^[a-f0-9]{64}$")


class AckInput(InputModel):
    node_id: str
    status: Literal["APPLIED", "REJECTED"]
    result: dict = Field(default_factory=dict)


class EventInput(InputModel):
    attempt_id: str
    seq: int = Field(ge=1, strict=True)
    type: Literal["STARTED", "METRIC", "LOG", "RESOURCE", "ARTIFACT", "SUCCEEDED", "FAILED", "CANCELLED"]
    timestamp: str
    data: dict = Field(default_factory=dict)


class EventBatchInput(InputModel):
    node_id: str
    events: list[EventInput] = Field(max_length=1000)
